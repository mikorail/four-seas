// Pick only the Shippori Mincho subsets that contain CJK glyphs the game actually uses,
// copy them to static/fonts and emit src/lib/fonts-cjk.css. Run after adding new glyphs:
//   node scripts/cjk-fonts.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, statSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const pkg = join(root, 'node_modules/@fontsource/shippori-mincho');

// collect every CJK / fullwidth char from source files
const chars = new Set();
function walk(dir) {
	for (const f of readdirSync(dir)) {
		const p = join(dir, f);
		if (statSync(p).isDirectory()) walk(p);
		else if (/\.(ts|svelte|css|html)$/.test(f) && !f.startsWith('i18n') && !f.endsWith('.gen.ts')) for (const ch of readFileSync(p, 'utf8')) if (/[　-鿿＀-￯]/.test(ch)) chars.add(ch.codePointAt(0));
	}
}
walk(join(root, 'src'));

const css = readFileSync(join(pkg, '700.css'), 'utf8');
const blocks = css.split('@font-face').slice(1).map((b) => '@font-face' + b.trim());
const keep = [];
for (const b of blocks) {
	const range = /unicode-range:\s*([^;]+);/.exec(b)?.[1] ?? '';
	const hit = range.split(',').some((r) => {
		const m = /U\+([0-9A-F]+)(?:-([0-9A-F]+))?/i.exec(r.trim());
		if (!m) return false;
		const lo = parseInt(m[1], 16);
		const hi = m[2] ? parseInt(m[2], 16) : lo;
		for (const c of chars) if (c >= lo && c <= hi) return true;
		return false;
	});
	if (hit) keep.push(b);
}

const out = join(root, 'static/fonts');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
let total = 0;
const rules = keep.map((b) => {
	const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(b)[1];
	copyFileSync(join(pkg, 'files', file), join(out, file));
	total += statSync(join(out, file)).size;
	// woff2 only, served from /fonts
	return b.replace(/src:[^;]+;/, `src: url(/fonts/${file}) format('woff2');`);
});
writeFileSync(join(root, 'src/lib/fonts-cjk.css'), `/* generated by scripts/cjk-fonts.mjs — ${chars.size} glyphs */\n` + rules.join('\n') + '\n');
console.log(`${chars.size} CJK glyphs → ${keep.length} subset files, ${(total / 1024).toFixed(0)} KB`);
