// Bundle src/content/**/*.md into src/lib/content/raw.gen.ts (so the engine works in the browser, tests and the sim alike).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

export function generateContent(root = new URL('..', import.meta.url).pathname) {
	const out = [];
	for (const kind of ['cards', 'campaigns']) {
		const dir = join(root, 'src/content', kind);
		if (!existsSync(dir)) continue;
		for (const f of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) out.push({ file: f, kind, src: readFileSync(join(dir, f), 'utf8') });
	}
	const body = `// GENERATED by scripts/content.mjs from src/content — do not edit.\nexport const RAW: { file: string; kind: 'cards' | 'campaigns'; src: string }[] = ${JSON.stringify(out, null, '\t')};\n`;
	const target = join(root, 'src/lib/content/raw.gen.ts');
	if (!existsSync(target) || readFileSync(target, 'utf8') !== body) writeFileSync(target, body);
	return out.length;
}

if (import.meta.url === `file://${process.argv[1]}`) console.log(`content: ${generateContent()} files bundled`);
