const DICTS: Record<Lang, Dict> = { en: {}, id, ja, zh };

let current = $state<Lang>('en');

export const i18n = {
	get lang() {
		return current;
	},
	set lang(v: Lang) {
		current = v;
		try {
			localStorage.setItem('four-seas:lang', v);
			document.documentElement.lang = v;
		} catch {}
	},
	load() {
		try {
			const v = localStorage.getItem('four-seas:lang') as Lang | null;
			if (v && v in LANGS) this.lang = v;
		} catch {}
	}
};

/** Translate an interface string; `{name}` placeholders are filled from `vars`. */
export function t(s: string, vars: Record<string, string | number> = {}): string {
	const tr = DICTS[current][s] ?? s;
	return tr.replace(/\{(\w+)\}/g, (_m, k) => String(vars[k] ?? `{${k}}`));
}
